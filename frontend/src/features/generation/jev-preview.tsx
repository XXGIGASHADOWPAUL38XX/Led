import { useContext, useEffect, useRef } from "react";
import { useGenerationPreview } from "@/api/hooks";
import type { Endpoint } from "@/api/protocol";
import { CatalogContext } from "../catalog/catalog-context";
import { layoutGraph } from "../graph/graph-layout";
import { connectionPath } from "../graph/connection-path";

export function JevPreview() {
  const preview = useGenerationPreview();
  const catalog = useContext(CatalogContext);
  const viewport = useRef<HTMLDivElement>(null);
  useEffect(() => {
    const element = viewport.current;
    if (element) element.scrollLeft = element.scrollWidth;
  }, [preview]);
  if (!preview) return <p className="mt-3 text-xs text-muted-foreground">Waiting for the first validated node…</p>;

  const nodes = preview.nodes.map((node) => ({
    ...node,
    inputs: node.ports.filter((port) => port.direction === "in"),
    outputs: node.ports.filter((port) => port.direction === "out"),
  }));
  const width = 260;
  const sizes = new Map(
    nodes.map((node) => [node.id, { width, height: 64 + Math.max(node.inputs.length, node.outputs.length) * 20 }]),
  );
  const positions = layoutGraph(preview.graph, sizes);
  const extent = {
    width: Math.max(300, ...nodes.map((node) => positions[node.id][0] + width + 24)),
    height: Math.max(160, ...nodes.map((node) => positions[node.id][1] + sizes.get(node.id)!.height + 24)),
  };
  const anchor = (endpoint: Endpoint, output: boolean) => {
    const node = nodes.find((item) => item.id === endpoint.nodeId)!;
    const index = (output ? node.outputs : node.inputs).findIndex((port) => port.name === endpoint.element);
    const [x, y] = positions[node.id];
    return { x: x + (output ? width : 0), y: y + 66 + index * 20 };
  };

  return (
    <div className="mt-4 space-y-2">
      <p className="text-xs text-violet-200">
        Draft preview · {nodes.length} nodes · {preview.graph.connections.length} connections{" "}
        <span className="text-muted-foreground">· Read only</span>
      </p>
      <div
        ref={viewport}
        tabIndex={0}
        aria-label="Jev draft graph preview"
        className="node-canvas max-h-80 overflow-auto rounded-lg border border-violet-400/20 outline-none focus-visible:ring-1 focus-visible:ring-violet-400"
      >
        <svg
          width={extent.width}
          height={extent.height}
          role="img"
          aria-label="Nodes and connections being generated by Jev"
          className="block"
        >
          {preview.graph.connections.map((edge) => (
            <path
              key={edge.id}
              d={connectionPath(anchor(edge.source, true), anchor(edge.target, false))}
              fill="none"
              className="stroke-primary"
              strokeWidth={2}
              strokeOpacity={0.65}
            >
              <title>
                {edge.source.nodeId}.{edge.source.element} → {edge.target.nodeId}.{edge.target.element}
              </title>
            </path>
          ))}
          {nodes.map((node, index) => (
            <g key={node.id} transform={`translate(${positions[node.id].join(",")})`}>
              <rect
                width={width}
                height={sizes.get(node.id)!.height}
                rx={12}
                className={`fill-zinc-900 ${index === nodes.length - 1 ? "stroke-primary" : "stroke-zinc-700"}`}
              />
              <text x={16} y={24} className="fill-zinc-200" fontSize={13} fontWeight={500}>
                {(catalog?.[node.type]?.title ?? node.type).slice(0, 32)}
              </text>
              <text x={16} y={43} className="fill-muted-foreground" fontSize={10}>
                {node.id.slice(0, 40)}
              </text>
              {[node.inputs, node.outputs].map((ports, side) =>
                ports.map((port, row) => (
                  <g key={`${side}:${port.name}`}>
                    <title>
                      {port.name} · {port.shape.length ? port.shape.join(" × ") : "scalar"}
                    </title>
                    <circle cx={side ? width : 0} cy={66 + row * 20} r={4} className="fill-primary" />
                    <text
                      x={side ? width - 12 : 12}
                      y={70 + row * 20}
                      textAnchor={side ? "end" : "start"}
                      className="fill-zinc-400"
                      fontSize={10}
                    >
                      {port.name.length > 18 ? `${port.name.slice(0, 17)}…` : port.name}
                    </text>
                  </g>
                )),
              )}
            </g>
          ))}
        </svg>
      </div>
    </div>
  );
}
